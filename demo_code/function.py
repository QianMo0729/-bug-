'''
================================================================================
 function.py —— 第 3 关：函数小镇
================================================================================
【这一关在游戏里怎么表现】
- 场景是一片"函数小镇"：每个函数 = 一栋小房子，门牌写函数名，
  门口的"招牌"写它的参数（形参），屋顶冒出的烟 = 返回值。
- 玩家在镇上跑腿，给函数"投递参数"，看它"吐出"返回值，
  直观理解：函数 = 输入(形参) → 处理 → 输出(return)。

【3 栋教学房子（常见函数类 bug）】
  1) add_label(text)            —— 作用域：函数内 global/局部变量误解
  2) make_team(member, team=[]) —— ☠ 可变默认参数坑（共享同一个 list）
  3) patched_checker(x)         —— 被人"事后篡改"过的函数（推理链线索③）

【推理链线索（承上启下）—— 关键的一关】
- 上一关确认"有人在造 bug"。这一关玩家会在 make_team 撞见经典的
  可变默认参数 bug；修它时翻看函数历史，发现 patched_checker 这栋房子
  墙上有一道新刷的漆，盖住了原作者，露出半行注释： # patched by ?????
- 这是第一处"人为痕迹"：bug 不是天生的，是**某个具体的人改出来的**。
- 【碎片③】= _trace() 的"比对 + 返回"两行，藏在 patched_checker 被篡改的函数体里。
================================================================================
'''
import agent_bot
import game_setup
import current_role
import bug_maker


# ============================================================================
#  房子 1：作用域 —— 局部变量改了不影响外面
# ============================================================================
counter = 0   # 镇子广场上的"全局计数牌"

def add_label(text):
    '''房间表现：屋里有个本地小白板(local)，墙外广场有块大牌子(global counter)。
    玩家以为在屋里 +1 会更新广场大牌子，结果广场纹丝不动——
    因为函数里直接赋值会新建一个"局部 counter"，遮住全局的。
    教学：要改全局得显式 global，否则赋值只作用于局部。'''
    agent_bot.bot_say("函数里有自己的'本地空间'。在里面新建的变量，出了门就消失。")

    counter = 0          # ← 看似在更新广场计数，其实新建了一个局部 counter（bug）
    counter += 1
    agent_bot.system_prompt(f"屋里 counter={counter}，可广场上的大牌子还是 {globals()['counter']}。")
    agent_bot.bot_say("想真正改广场那块牌子，得在函数开头写 global counter 声明一下。")
    return text.upper()  # 顺手演示：函数有返回值，烟囱冒出大写的招牌


# ============================================================================
#  房子 2：☠ 可变默认参数坑（整关最阴险的 bug）
# ============================================================================
def make_team(member, team=[]):          # ← bug：默认值 [] 只在定义时创建一次，被所有调用共享
    '''房间表现：一栋"组队登记处"。第一个玩家登记，名单上出现自己，正常。
    第二个玩家来登记，名单上却**已经有上一个人**——明明每次该是空名单！
    可视化：登记台下面藏着一张"永远不换"的旧纸（同一个 list 对象被反复 append）。
    正解：默认参数用 None，进函数再新建 team = []，每次都是干净的新名单。'''
    agent_bot.bot_say("这家组队登记处，每次应该给你一张空白名单才对。")
    team.append(member)
    return team

def make_team_fixed(member, team=None):  # 玩家拾取并替换上去的正解
    if team is None:
        team = []                        # 每次调用都新建，互不污染
    team.append(member)
    return team


# ============================================================================
#  房子 3：被"事后篡改"过的函数 —— 推理链线索③ + 碎片③
# ============================================================================
def patched_checker(x):
    '''房间表现：这栋房子和别的不一样——墙是新刷的漆，盖住了原作者署名。
    玩家用"刮漆"动作(蹭墙)刮掉新漆，露出底层注释 # patched by ?????
    地面裂缝里嵌着【碎片③】（两行 _trace 的代码：比对作者 + 返回命中）。
    教学顺带：== 比较"值是否相等"，is 比较"是不是同一个对象"，二者不可混用。'''
    agent_bot.bot_say("这栋房子被人重新刷过漆，像是想盖掉原来的作者……")
    agent_bot.system_prompt("蹭一下墙：# patched by ?????（落款被涂掉了）")

    # —— 玩家刮开后，地缝里的【碎片③】显形（这是 _trace 的后半段）——
    game_setup.spawn_fragment(3, lines=[
        "        if bug.author is sig:   # ← 这里埋着一个 is/== 的 bug，留到 bug_maker 关修",
        "            found.append(bug)",
        "    return found",
    ])
    agent_bot.bot_say("碎片③到手。它和之前的两片拼起来，像是一个'查作者'的函数残骸。")
    agent_bot.bot_say("是谁在偷偷篡改函数？这串 ????? 得想办法还原成真正的签名。")
    bug_maker.log_patch("patched_checker", author="?????")
    return x is not None
